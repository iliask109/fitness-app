// Builds supabase/setup.sql (a fresh install in one paste) from the individual SQL files, in order.
// Run after adding or changing a supabase/update-*.sql file: npm run sql:setup
import { readFileSync, writeFileSync } from 'node:fs';

const FILES = [
  'schema.sql',
  'admin.sql',
  'update-2-signup.sql',
  'update-3-onboarding.sql',
  'update-4-schedule.sql',
  'update-5-reminders.sql',
  'update-6-program-templates.sql',
  'update-7-gender.sql',
  'update-8-goal-period.sql',
  'update-9-auto-nutrition.sql',
  'update-11-delete-account.sql',
  'update-12-language.sql',
  'update-14-meal-plan-and-messages.sql',
  'update-15-security.sql',
];

const parts = FILES.map((f) => `-- ===================== ${f} =====================\n\n${readFileSync(`supabase/${f}`, 'utf8').trim()}\n`);
writeFileSync('supabase/setup.sql', [
  '-- FitLogix: full database setup for a NEW Supabase project. Generated by `npm run sql:setup`; do not edit by hand.',
  '-- Supabase: SQL Editor -> New query -> paste this whole file -> Run. Safe to run again.',
  '-- Existing projects: run only the update-*.sql files you have not run yet (the admin area lists them).',
  '-- Afterwards: make yourself admin (bottom of admin.sql) and, for reminders, run update-5b-schedule-reminders.sql.',
  '',
  ...parts,
].join('\n'));
console.log('supabase/setup.sql written from', FILES.length, 'files');
